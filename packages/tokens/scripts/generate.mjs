// Generates the native design tokens from tokens.json:
//   apps/ios/Packages/TuneKit/Sources/DesignSystem/Tokens.swift
//   apps/android/core/designsystem/src/main/java/com/tunecompanion/app/designsystem/Tokens.kt
// The outputs are committed so the apps build without Node; the drift test fails when they are stale.
import { readFileSync, writeFileSync } from "node:fs";

const root = new URL("../../../", import.meta.url);
export const OUTPUTS = {
  swift: new URL("apps/ios/Packages/TuneKit/Sources/DesignSystem/Tokens.swift", root),
  kotlin: new URL("apps/android/core/designsystem/src/main/java/com/tunecompanion/app/designsystem/Tokens.kt", root),
};

const camel = (name) => name.replace(/-(\w)/g, (_, c) => c.toUpperCase());

/** "#fff" or "#c8642a" or "{brand-dot}" → 0xRRGGBB, following aliases. */
function rgb(tokens, value, mode) {
  const alias = value.match(/^\{([\w-]+)\}$/);
  if (alias) return rgb(tokens, tokens.color[alias[1]][mode], mode);
  let hex = value.slice(1);
  if (hex.length === 3) hex = [...hex].map((c) => c + c).join("");
  if (hex.length !== 6) throw new Error(`Unsupported colour ${value}`);
  return hex.toUpperCase();
}

export function swift(tokens) {
  const colours = Object.entries(tokens.color).map(([name, c]) =>
    `    public static let ${camel(name)} = Color(light: 0x${rgb(tokens, c.light, "light")}, dark: 0x${rgb(tokens, c.dark, "dark")})`).join("\n");
  const radii = Object.entries(tokens.radius).map(([name, r]) => `    public static let ${camel(name.replace(/^radius-?/, "") || "base")}: CGFloat = ${r}`).join("\n");
  const [x1, y1, x2, y2] = tokens.motion.ease;
  return `// Generated by packages/tokens (npm run generate -w packages/tokens). Do not edit.
import SwiftUI

public enum Palette {
${colours}
}

public enum Radius {
${radii}
}

public enum Motion {
    /// The web's --ease and --duration: a quick ease-out for state changes.
    public static let standard = Animation.timingCurve(${x1}, ${y1}, ${x2}, ${y2}, duration: ${tokens.motion.durationMs / 1000})
}
`;
}

export function kotlin(tokens) {
  const colours = Object.entries(tokens.color).map(([name, c]) =>
    `    val ${camel(name)} = ColorPair(Color(0xFF${rgb(tokens, c.light, "light")}), Color(0xFF${rgb(tokens, c.dark, "dark")}))`).join("\n");
  const radii = Object.entries(tokens.radius).map(([name, r]) => `    val ${camel(name.replace(/^radius-?/, "") || "base")} = ${r}.dp`).join("\n");
  const [x1, y1, x2, y2] = tokens.motion.ease;
  return `// Generated by packages/tokens (npm run generate -w packages/tokens). Do not edit.
package com.tunecompanion.app.designsystem

import androidx.compose.animation.core.CubicBezierEasing
import androidx.compose.ui.graphics.Color
import androidx.compose.ui.unit.dp

data class ColorPair(val light: Color, val dark: Color) {
    fun pick(dark: Boolean): Color = if (dark) this.dark else light
}

object Palette {
${colours}
}

object Radius {
${radii}
}

object Motion {
    /** The web's --ease and --duration: a quick ease-out for state changes. */
    val ease = CubicBezierEasing(${x1}f, ${y1}f, ${x2}f, ${y2}f)
    const val DURATION_MS = ${tokens.motion.durationMs}
}
`;
}

export const load = () => JSON.parse(readFileSync(new URL("../tokens.json", import.meta.url), "utf8"));

if (import.meta.url === `file://${process.argv[1]}`) {
  const tokens = load();
  writeFileSync(OUTPUTS.swift, swift(tokens));
  writeFileSync(OUTPUTS.kotlin, kotlin(tokens));
  console.log("Wrote Tokens.swift and Tokens.kt");
}
